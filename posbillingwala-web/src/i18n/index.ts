export type MessageKey = keyof typeof dict.en

interface I18nState {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: MessageKey) => string
}

export const useI18n = create<I18nState>()(
  persist(
    (set, get) => ({
      locale: 'en',
      setLocale(locale) {
        set({ locale })
      },
      t(key) {
        const { locale } = get()
        return dict[locale][key] ?? dict.en[key] ?? key
      },
    }),
    { name: 'pb-locale' },
  ),
)
